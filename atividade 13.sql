-- 5.1. Criação da Tabela (Corrigida conforme MER do PDF)
CREATE TABLE LOG_ALTERACOES (
    ID_LOG NUMBER NOT NULL,
    ACAO VARCHAR2(12) NOT NULL,
    TABELA VARCHAR2(30) NOT NULL,
    DATA_EVENTO DATE NOT NULL,
    CONSTRAINT PK_LOG_ALTERACOES PRIMARY KEY (ID_LOG)
);

-- 5.2. Criação da Sequence
CREATE SEQUENCE SEQ_ID_LOG_ALTERACOES
START WITH 1
INCREMENT BY 1;

-- 5.3. Criação da Trigger (Oracle 10g)
CREATE OR REPLACE TRIGGER TRG_LOG_ALTR_BI
BEFORE INSERT ON LOG_ALTERACOES
FOR EACH ROW
BEGIN
    -- Verifica se houve tentativa de inserir o ID manualmente
    IF :NEW.ID_LOG IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20001, 'Não é permitido inserir manualmente o ID');
    ELSE
        -- Gera o ID automaticamente usando a sequence (padrão Oracle 10g)
        SELECT SEQ_ID_LOG_ALTERACOES.NEXTVAL INTO :NEW.ID_LOG FROM DUAL;
    END IF;
END;
